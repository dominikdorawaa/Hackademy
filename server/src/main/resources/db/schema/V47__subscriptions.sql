CREATE TABLE subscriptions (
    user_id bigint NOT NULL,
    active_until timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT pk_subscriptions PRIMARY KEY (user_id),
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE subscription_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint,
    plan_id varchar(16) NOT NULL,
    days integer NOT NULL,
    coins integer NOT NULL,
    price_minor integer NOT NULL,
    currency varchar(3) NOT NULL,
    provider varchar(16) NOT NULL,
    provider_reference varchar(128),
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    created_at timestamp(6) NOT NULL DEFAULT now(),
    paid_at timestamp(6),
    CONSTRAINT pk_subscription_orders PRIMARY KEY (id),
    CONSTRAINT fk_subscription_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_subscription_orders_status CHECK (status IN ('PENDING', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_subscription_orders_amounts CHECK (days > 0 AND coins >= 0 AND price_minor > 0),
    CONSTRAINT uq_subscription_orders_provider_reference UNIQUE (provider, provider_reference)
);

CREATE INDEX idx_subscription_orders_user ON subscription_orders (user_id, created_at DESC);

