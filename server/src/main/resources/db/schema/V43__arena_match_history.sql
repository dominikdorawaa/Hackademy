CREATE TABLE arena_matches (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    game_id varchar(64) NOT NULL,
    opponent_name varchar(64) NOT NULL,
    result varchar(8) NOT NULL,
    elo_change integer NOT NULL DEFAULT 0,
    finished_at timestamp(6) NOT NULL,
    CONSTRAINT pk_arena_matches PRIMARY KEY (id),
    CONSTRAINT fk_arena_matches_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_arena_matches_result CHECK (result IN ('WIN', 'LOSS', 'DRAW')),
    CONSTRAINT uq_arena_matches_game_user UNIQUE (game_id, user_id)
);

CREATE INDEX idx_arena_matches_user_finished ON arena_matches (user_id, finished_at DESC, id DESC);
