CREATE TABLE wallets (
    user_id bigint NOT NULL,
    balance bigint NOT NULL DEFAULT 0,
    updated_at timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT pk_wallets PRIMARY KEY (user_id),
    CONSTRAINT fk_wallets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_wallets_balance CHECK (balance >= 0)
);

CREATE TABLE owned_items (
    user_id bigint NOT NULL,
    item_id varchar(32) NOT NULL,
    acquired_at timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT pk_owned_items PRIMARY KEY (user_id, item_id),
    CONSTRAINT fk_owned_items_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE top_up_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint,
    package_id varchar(16) NOT NULL,
    coins integer NOT NULL,
    price_minor integer NOT NULL,
    currency varchar(3) NOT NULL,
    provider varchar(16) NOT NULL,
    provider_reference varchar(128),
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    created_at timestamp(6) NOT NULL DEFAULT now(),
    paid_at timestamp(6),
    CONSTRAINT pk_top_up_orders PRIMARY KEY (id),
    CONSTRAINT fk_top_up_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_top_up_orders_status CHECK (status IN ('PENDING', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_top_up_orders_amounts CHECK (coins > 0 AND price_minor > 0),
    CONSTRAINT uq_top_up_orders_provider_reference UNIQUE (provider, provider_reference)
);

CREATE INDEX idx_top_up_orders_user ON top_up_orders (user_id, created_at DESC);

CREATE TABLE wallet_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    amount bigint NOT NULL,
    balance_after bigint NOT NULL,
    kind varchar(16) NOT NULL,
    item_id varchar(32),
    order_id bigint,
    admin_id bigint,
    reason varchar(200),
    created_at timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT pk_wallet_transactions PRIMARY KEY (id),
    CONSTRAINT fk_wallet_transactions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_wallet_transactions_order FOREIGN KEY (order_id) REFERENCES top_up_orders (id) ON DELETE SET NULL,
    CONSTRAINT fk_wallet_transactions_admin FOREIGN KEY (admin_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_wallet_transactions_kind CHECK (kind IN ('PURCHASE', 'TOP_UP', 'ADMIN')),
    CONSTRAINT ck_wallet_transactions_amount CHECK (amount <> 0 AND balance_after >= 0)
);

CREATE INDEX idx_wallet_transactions_user ON wallet_transactions (user_id, created_at DESC, id DESC);

