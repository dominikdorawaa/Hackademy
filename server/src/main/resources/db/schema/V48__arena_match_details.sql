ALTER TABLE arena_matches
    ADD COLUMN opponent_id bigint,
    ADD COLUMN opponent_bot boolean NOT NULL DEFAULT false,
    ADD COLUMN finish_reason varchar(16),
    ADD COLUMN elo_before integer,
    ADD COLUMN opponent_elo integer,
    ADD COLUMN hp integer,
    ADD COLUMN opponent_hp integer,
    ADD COLUMN duration_seconds integer,
    ADD COLUMN opponent_avatar text,
    ADD CONSTRAINT fk_arena_matches_opponent FOREIGN KEY (opponent_id) REFERENCES users (id) ON DELETE SET NULL;

UPDATE arena_matches m
SET opponent_id = other.user_id
FROM arena_matches other
WHERE other.game_id = m.game_id AND other.user_id <> m.user_id;

CREATE TABLE arena_match_rounds (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    match_id bigint NOT NULL,
    round_number integer NOT NULL,
    question_id bigint,
    content text NOT NULL,
    category varchar(32) NOT NULL,
    difficulty varchar(16),
    answer_1 text NOT NULL,
    answer_2 text NOT NULL,
    answer_3 text NOT NULL,
    answer_4 text NOT NULL,
    correct_answer smallint NOT NULL,
    choice smallint,
    answer_millis integer,
    opponent_choice smallint,
    opponent_answer_millis integer,
    hp_after integer NOT NULL,
    opponent_hp_after integer NOT NULL,
    CONSTRAINT pk_arena_match_rounds PRIMARY KEY (id),
    CONSTRAINT fk_arena_match_rounds_match FOREIGN KEY (match_id) REFERENCES arena_matches (id) ON DELETE CASCADE,
    CONSTRAINT fk_arena_match_rounds_question FOREIGN KEY (question_id) REFERENCES arena_questions (id) ON DELETE SET NULL,
    CONSTRAINT uq_arena_match_rounds_round UNIQUE (match_id, round_number),
    CONSTRAINT ck_arena_match_rounds_correct CHECK (correct_answer BETWEEN 0 AND 3),
    CONSTRAINT ck_arena_match_rounds_choice CHECK (choice IS NULL OR choice BETWEEN 0 AND 3),
    CONSTRAINT ck_arena_match_rounds_opponent_choice CHECK (opponent_choice IS NULL OR opponent_choice BETWEEN 0 AND 3)
);
