CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    username varchar(20) NOT NULL,
    email varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    bio text,
    role varchar(255) NOT NULL,
    points integer NOT NULL,
    streak integer NOT NULL,
    elo integer NOT NULL DEFAULT 500,
    last_solved_date date,
    muted_until timestamp(6),
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN', 'EXPERT')),
    CONSTRAINT ck_users_points CHECK (points >= 0),
    CONSTRAINT ck_users_streak CHECK (streak >= 0)
);

CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username));
CREATE INDEX idx_users_points ON users (points DESC);
CREATE INDEX idx_users_elo ON users (elo DESC);

CREATE TABLE badges (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(255) NOT NULL,
    description varchar(255) NOT NULL,
    icon varchar(255) NOT NULL,
    condition_type varchar(255) NOT NULL,
    condition_value integer NOT NULL,
    CONSTRAINT pk_badges PRIMARY KEY (id),
    CONSTRAINT uq_badges_name UNIQUE (name),
    CONSTRAINT ck_badges_condition_type CHECK (condition_type IN ('POINTS', 'STREAK', 'SOLVED_COUNT', 'FRIENDS_COUNT')),
    CONSTRAINT ck_badges_condition_value CHECK (condition_value >= 0)
);

CREATE TABLE user_badges (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    badge_id bigint NOT NULL,
    earned_at timestamp(6) NOT NULL,
    CONSTRAINT pk_user_badges PRIMARY KEY (id),
    CONSTRAINT uq_user_badges_user_badge UNIQUE (user_id, badge_id),
    CONSTRAINT fk_user_badges_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_badges_badge FOREIGN KEY (badge_id) REFERENCES badges (id) ON DELETE CASCADE
);

CREATE INDEX idx_user_badges_badge ON user_badges (badge_id);

CREATE TABLE rooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    title varchar(255) NOT NULL,
    description text NOT NULL,
    short_description varchar(255),
    difficulty varchar(255) NOT NULL,
    category varchar(255) NOT NULL,
    points integer NOT NULL,
    flag varchar(255) NOT NULL,
    solutions_count integer NOT NULL,
    requires_vpn boolean NOT NULL,
    room_type varchar(16) NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    CONSTRAINT pk_rooms PRIMARY KEY (id),
    CONSTRAINT uq_rooms_title UNIQUE (title),
    CONSTRAINT ck_rooms_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD', 'INSANE')),
    CONSTRAINT ck_rooms_room_type CHECK (room_type IN ('CTF', 'PATH')),
    CONSTRAINT ck_rooms_points CHECK (points >= 0),
    CONSTRAINT ck_rooms_solutions_count CHECK (solutions_count >= 0)
);

CREATE TABLE room_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    title varchar(255) NOT NULL,
    content text NOT NULL,
    question text,
    answer varchar(255),
    room_id bigint NOT NULL,
    sort_order integer NOT NULL,
    CONSTRAINT pk_room_tasks PRIMARY KEY (id),
    CONSTRAINT fk_room_tasks_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT ck_room_tasks_sort_order CHECK (sort_order >= 0)
);

CREATE INDEX idx_room_tasks_room_sort ON room_tasks (room_id, sort_order);

CREATE TABLE hints (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    description text NOT NULL,
    room_id bigint NOT NULL,
    CONSTRAINT pk_hints PRIMARY KEY (id),
    CONSTRAINT fk_hints_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE
);

CREATE INDEX idx_hints_room ON hints (room_id);

CREATE TABLE room_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    file_name varchar(255),
    file_type varchar(255),
    data bytea,
    room_id bigint NOT NULL,
