CREATE TABLE friendships (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    requester_id bigint NOT NULL,
    receiver_id bigint NOT NULL,
    status varchar(255) NOT NULL,
    requester_wins integer NOT NULL,
    receiver_wins integer NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT pk_friendships PRIMARY KEY (id),
    CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_receiver FOREIGN KEY (receiver_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED')),
    CONSTRAINT ck_friendships_not_self CHECK (requester_id <> receiver_id),
    CONSTRAINT ck_friendships_wins CHECK (requester_wins >= 0 AND receiver_wins >= 0)
);

CREATE UNIQUE INDEX uq_friendships_pair ON friendships (least(requester_id, receiver_id), greatest(requester_id, receiver_id));
CREATE INDEX idx_friendships_receiver ON friendships (receiver_id);

CREATE TABLE chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    game_id varchar(255) NOT NULL,
    sender_id bigint NOT NULL,
    sender_username varchar(255) NOT NULL,
    content varchar(500) NOT NULL,
    reported boolean NOT NULL,
    sent_at timestamp(6) NOT NULL,
    CONSTRAINT pk_chat_messages PRIMARY KEY (id),
    CONSTRAINT fk_chat_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_chat_messages_game_sent_at ON chat_messages (game_id, sent_at);
CREATE INDEX idx_chat_messages_sender ON chat_messages (sender_id);
CREATE INDEX idx_chat_messages_reported_sent_at ON chat_messages (sent_at DESC) WHERE reported;

