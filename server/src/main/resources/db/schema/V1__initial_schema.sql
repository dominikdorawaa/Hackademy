CREATE INDEX idx_path_rooms_path_sort ON path_rooms (path_id, sort_order);
CREATE INDEX idx_path_rooms_room ON path_rooms (room_id);

CREATE TABLE path_enrollments (
    user_id bigint NOT NULL,
