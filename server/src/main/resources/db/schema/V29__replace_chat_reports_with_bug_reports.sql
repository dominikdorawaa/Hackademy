DROP TABLE chat_messages;

ALTER TABLE users DROP COLUMN muted_until;

CREATE TABLE bug_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    reporter_id bigint NOT NULL,
    source varchar(16) NOT NULL,
    room_id bigint,
    task_id bigint,
    game_id varchar(64),
    page_path varchar(300),
    description varchar(2000) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'OPEN',
    created_at timestamp(6) NOT NULL,
    resolved_at timestamp(6),
    CONSTRAINT pk_bug_reports PRIMARY KEY (id),
    CONSTRAINT fk_bug_reports_reporter FOREIGN KEY (reporter_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_bug_reports_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE SET NULL,
    CONSTRAINT fk_bug_reports_task FOREIGN KEY (task_id) REFERENCES room_tasks (id) ON DELETE SET NULL,
    CONSTRAINT ck_bug_reports_source CHECK (source IN ('ROOM', 'ARENA')),
    CONSTRAINT ck_bug_reports_status CHECK (status IN ('OPEN', 'RESOLVED')),
    CONSTRAINT ck_bug_reports_description CHECK (char_length(description) BETWEEN 10 AND 2000)
);

CREATE INDEX idx_bug_reports_created ON bug_reports (created_at DESC, id DESC);
CREATE INDEX idx_bug_reports_status_created ON bug_reports (status, created_at DESC, id DESC);
CREATE INDEX idx_bug_reports_reporter_created ON bug_reports (reporter_id, created_at);
CREATE INDEX idx_bug_reports_room ON bug_reports (room_id);
CREATE INDEX idx_bug_reports_task ON bug_reports (task_id);
